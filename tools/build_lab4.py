        "связывание двух запросов прогноза оператором flatMap и обработку "
        "неизвестного города. ExportTests проверяют соответствие чек-листа "
        "содержимому чемодана, кодирование и обратное чтение файла JSON, "
        "текстовое представление, а также работу конвейера задержки ввода: "
        "быстрый набор четырёх символов приводит к одной выборке, а повтор того же "
